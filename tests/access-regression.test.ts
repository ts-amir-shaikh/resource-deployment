const EXPECTED_SHA256 = '40fc8261138b20b750d9707d87b508ba858cd8ba048dc2f42d5c5b8280b8ebdc';

describe('existing role policy is unchanged', () => {
  it('covers 9 roles on 166 paths', () => {
    expect(ROLES).toHaveLength(9);
    expect(PATHS).toHaveLength(166);
  });

  it('every role gets the same access and write decision as before the reporting API', () => {
    const rows: string[] = [];
    for (const role of ROLES) {
      for (const p of PATHS) rows.push(`${role} ${p} ${canAccess(role, p) ? 'A' : '-'}${canWrite(role, p) ? 'W' : '-'}`);
    }
    expect(createHash('sha256').update(rows.join('\n')).digest('hex')).toBe(EXPECTED_SHA256);
  });
});
